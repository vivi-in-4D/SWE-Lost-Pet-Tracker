DROP TABLE IF EXISTS AIAttribute, Photo, PetMarking, PetColor,
                     Post, AuthCode, UseFor2FA, Email, ContactMethod,
                     Account, Settings CASCADE;

CREATE TABLE Settings (
    SettingsID              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TextScoreWeight         FLOAT NOT NULL,
    ImageScoreWeight        FLOAT NOT NULL,
    AttributeScoreWeight    FLOAT NOT NULL,
    MatchRadiusWeight       FLOAT NOT NULL,
    OverallScoreThreshold   FLOAT NOT NULL,
    BaseSigma               FLOAT NOT NULL,
    RadiusSigmaGrowth       FLOAT NOT NULL,
    RadiusSigmaCap          FLOAT NOT NULL,
    RadiusDeletionFrequency INTERVAL,
    AuthCodeLifetime        INTERVAL NOT NULL CHECK (AuthCodeLifetime > INTERVAL '0'),
    CanPost                 BOOLEAN NOT NULL
);

CREATE TABLE Account (
    AccountID      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SettingsID     INT NOT NULL REFERENCES Settings (SettingsID),
    AccountNumHash VARCHAR(255) NOT NULL UNIQUE,
    CreatedAt      TIMESTAMPTZ NOT NULL DEFAULT now(),
    LastActiveAt   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE ContactMethod (
    AccountID  BIGINT NOT NULL REFERENCES Account (AccountID) ON DELETE CASCADE,
    ContactID  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Visibility VARCHAR(10) NOT NULL CHECK (Visibility IN ('public', 'email_only')),
    PRIMARY KEY (AccountID, ContactID)
);

CREATE TABLE Email (
    AccountID    BIGINT NOT NULL,
    ContactID    BIGINT NOT NULL,
    EmailAddress VARCHAR(255) NOT NULL
                 CHECK (EmailAddress ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    VerifiedAt   TIMESTAMPTZ,
    PRIMARY KEY (AccountID, ContactID),
    FOREIGN KEY (AccountID, ContactID)
        REFERENCES ContactMethod (AccountID, ContactID) ON DELETE CASCADE
);

CREATE TABLE UseFor2FA (
    AccountID BIGINT PRIMARY KEY REFERENCES Account (AccountID) ON DELETE CASCADE,
    ContactID BIGINT NOT NULL,
    Private   BOOLEAN NOT NULL DEFAULT false,
    FOREIGN KEY (AccountID, ContactID)
        REFERENCES Email (AccountID, ContactID) ON DELETE CASCADE
);

CREATE TABLE AuthCode (
    AccountID BIGINT NOT NULL REFERENCES Account (AccountID) ON DELETE CASCADE,
    CodeID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CodeHash  VARCHAR(255) NOT NULL,
    CreatedAt TIMESTAMPTZ NOT NULL DEFAULT now(),
    UsedAt    TIMESTAMPTZ CHECK (UsedAt >= CreatedAt),
    PRIMARY KEY (AccountID, CodeID)
);

CREATE TABLE Post (
    PostID        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AccountID     BIGINT NOT NULL UNIQUE REFERENCES Account (AccountID) ON DELETE CASCADE,
    PostType      VARCHAR(5) NOT NULL CHECK (PostType IN ('lost', 'found')),
    Status        VARCHAR(20) NOT NULL DEFAULT 'unverified'
                  CHECK (Status IN ('unverified', 'active', 'hidden')),
    Title         VARCHAR(100) NOT NULL CHECK (btrim(Title) <> ''),
    Description   TEXT,
    Species       VARCHAR(50) NOT NULL CHECK (btrim(Species) <> ''),
    Breed         VARCHAR(100),
    Weight        FLOAT CHECK (Weight > 0),
    Sex           VARCHAR(7) CHECK (Sex IN ('male', 'female', 'unknown')),
    Latitude      FLOAT NOT NULL CHECK (Latitude BETWEEN -90 AND 90),
    Longitude     FLOAT NOT NULL CHECK (Longitude BETWEEN -180 AND 180),
    PlaceID       VARCHAR(255),
    LostOrFoundAt TIMESTAMPTZ NOT NULL,
    CreatedAt     TIMESTAMPTZ NOT NULL DEFAULT now(),
    ResolvedAt    TIMESTAMPTZ,
    CHECK (LostOrFoundAt <= CreatedAt),
    CHECK (ResolvedAt IS NULL OR ResolvedAt >= CreatedAt)
);

CREATE TABLE PetColor (
    PostID BIGINT NOT NULL REFERENCES Post (PostID) ON DELETE CASCADE,
    Color  VARCHAR(30) NOT NULL CHECK (btrim(Color) <> ''),
    PRIMARY KEY (PostID, Color)
);

CREATE TABLE PetMarking (
    PostID  BIGINT NOT NULL REFERENCES Post (PostID) ON DELETE CASCADE,
    Marking VARCHAR(255) NOT NULL CHECK (btrim(Marking) <> ''),
    PRIMARY KEY (PostID, Marking)
);

CREATE TABLE Photo (
    PostID         BIGINT NOT NULL REFERENCES Post (PostID) ON DELETE CASCADE,
    PhotoID        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    FilePath       VARCHAR(500) NOT NULL CHECK (FilePath ~* '\.(jpe?g|png|webp|heic)$'),
    UploadedAt     TIMESTAMPTZ NOT NULL DEFAULT now(),
    ModelVersion   VARCHAR(50),
    AIReviewStatus BOOLEAN NOT NULL DEFAULT false,
    PRIMARY KEY (PostID, PhotoID)
);

CREATE TABLE AIAttribute (
    PostID         BIGINT NOT NULL REFERENCES Post (PostID) ON DELETE CASCADE,
    AttributeID    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    AttributeName  VARCHAR(50) NOT NULL,
    AttributeValue VARCHAR(255) NOT NULL,
    Confidence     FLOAT CHECK (Confidence BETWEEN 0 AND 1),
    ModelVersion   VARCHAR(50),
    PRIMARY KEY (PostID, AttributeID)
);

CREATE INDEX idx_email_address ON Email (lower(EmailAddress));
CREATE INDEX idx_post_status ON Post (PostType, Status);
CREATE INDEX idx_post_location ON Post (Latitude, Longitude);
